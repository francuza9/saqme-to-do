#!/usr/bin/env node
// Generates desktop/mcp-tools.json from worker/src/mcp.js: the tools, instructions and protocol versions of the
// Windows app's local server for Claude Desktop (desktop/mcp-server.ps1), so it describes its tools in exactly the
// Worker's words and shapes (LOCAL_TOOLS, LOCAL_INSTRUCTIONS).
//   node scripts/build-mcp-tools.mjs           write it
//   node scripts/build-mcp-tools.mjs --check   exit 1 if it is out of date (also enforced by the tests)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LOCAL_INSTRUCTIONS, LOCAL_TOOLS, PROTOCOL_VERSIONS } from '../worker/src/mcp.js';
import { DELETE_LIMIT } from '../worker/src/connector.js';

export const path = join(dirname(fileURLToPath(import.meta.url)), '..', 'desktop', 'mcp-tools.json');

export function build() {
  return `${JSON.stringify({
    about: 'Generated by scripts/build-mcp-tools.mjs from worker/src/mcp.js: do not edit.',
    protocolVersions: PROTOCOL_VERSIONS,
    instructions: LOCAL_INSTRUCTIONS,
    deleteLimit: DELETE_LIMIT,
    tools: LOCAL_TOOLS,
  }, null, 1)}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = build();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(path, 'utf8'); } catch { /* missing */ }
    if (cur !== text) { console.error('desktop/mcp-tools.json is out of date: run node scripts/build-mcp-tools.mjs'); process.exit(1); }
  } else writeFileSync(path, text);
}
